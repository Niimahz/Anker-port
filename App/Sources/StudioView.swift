import SwiftUI
import UniformTypeIdentifiers

struct StudioView: View {
    @State private var showImporter = false
    @State private var report: GameReport?
    @State private var errorMessage: String?
    @State private var runtime: RuntimeKind = .madeira
    @State private var profileURL: URL?

    var body: some View {
        NavigationStack {
            List {
                Section("Game intake") {
                    Button("Select installed PC game folder") { showImporter = true }
                    Text("Read-only PE analysis. Windows files are never executed.")
                        .font(.caption).foregroundStyle(.secondary)
                }
                if let report {
                    Section("Scan: \(report.name)") {
                        Text("\(report.executables.count) EXE/DLL files • \(report.scripts.count) BAT/CMD scripts")
                        ForEach(report.executables) { file in
                            VStack(alignment: .leading, spacing: 5) {
                                Text(file.path).font(.headline)
                                Text("\(file.architecture) · \(file.format)").font(.subheadline)
                                if !file.importedDLLs.isEmpty {
                                    Text("Imports: " + file.importedDLLs.joined(separator: ", "))
                                        .font(.caption).textSelection(.enabled)
                                }
                                if let error = file.error {
                                    Text(error).font(.caption).foregroundStyle(.orange)
                                }
                            }
                        }
                        ForEach(report.scripts, id: \.self) { script in
                            Text("Script: \(script)")
                        }
                        ForEach(report.warnings, id: \.self) { warning in
                            Text(warning).foregroundStyle(.orange)
                        }
                    }
                    Section("Compatibility profile") {
                        Picker("Runtime", selection: $runtime) {
                            ForEach(RuntimeKind.allCases) { kind in
                                Text(kind.rawValue).tag(kind)
                            }
                        }
                        Button("Export untested profile JSON") { exportProfile() }
                        if let profileURL { ShareLink("Share profile", item: profileURL) }
                        Text("Runtime launch and standalone IPA export are not implemented.")
                            .font(.caption).foregroundStyle(.secondary)
                    }
                }
                if let errorMessage {
                    Section("Error") { Text(errorMessage).foregroundStyle(.red) }
                }
            }
            .navigationTitle("Anker Port Studio")
            .fileImporter(isPresented: $showImporter, allowedContentTypes: [.folder]) { result in
                switch result {
                case .success(let url):
                    let access = url.startAccessingSecurityScopedResource()
                    defer { if access { url.stopAccessingSecurityScopedResource() } }
                    do {
                        report = try GameAnalyzer.analyze(folder: url)
                        profileURL = nil
                        errorMessage = nil
                    } catch { errorMessage = error.localizedDescription }
                case .failure(let error): errorMessage = error.localizedDescription
                }
            }
        }
    }

    private func exportProfile() {
        guard let report, let candidate = report.executables.first(where: {
            $0.path.lowercased().hasSuffix(".exe") && $0.error == nil
        }) else {
            errorMessage = "No valid EXE found"
            return
        }
        let profile = CompatibilityProfile(
            schemaVersion: 1, gameName: report.name,
            executable: candidate.path, architecture: candidate.architecture,
            runtime: runtime, status: .untested, launchArguments: [],
            environment: [:], notes: ["Generated by static analysis only; runtime unverified"]
        )
        do {
            let url = FileManager.default.temporaryDirectory.appendingPathComponent("game-profile.json")
            let encoder = JSONEncoder()
            encoder.outputFormatting = [.prettyPrinted, .sortedKeys]
            try encoder.encode(profile).write(to: url, options: .atomic)
            profileURL = url
            errorMessage = nil
        } catch { errorMessage = error.localizedDescription }
    }
}
